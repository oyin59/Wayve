// Calculates straight-line distance in kilometers between two areas
export const getDistanceBetween = (area1, area2) => {
  if (!area1 || !area2) return Infinity;

  // Normalize potential legacy names (e.g., "Wuse 2" or "Central Area" mapped to new list)
  const norm1 = area1.includes("Wuse") ? "Wuse" : area1.includes("CBD") || area1.includes("Central") ? "Central Business District (CBD)" : area1;
  const norm2 = area2.includes("Wuse") ? "Wuse" : area2.includes("CBD") || area2.includes("Central") ? "Central Business District (CBD)" : area2;

  if (norm1 === norm2) return 1.0;

  const coord1 = AREA_COORDINATES[norm1];
  const coord2 = AREA_COORDINATES[norm2];

  if (!coord1 || !coord2) return Infinity;

  const R = 6371; // Earth's radius in KM
  const dLat = ((coord2.lat - coord1.lat) * Math.PI) / 180;
  const dLng = ((coord2.lng - coord1.lng) * Math.PI) / 180;

  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((coord1.lat * Math.PI) / 180) *
      Math.cos((coord2.lat * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);

  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const dist = R * c;

  // Multiply by road curvature factor (~1.3x) for accurate driving estimation
  return Math.round(dist * 1.3 * 10) / 10;
};

